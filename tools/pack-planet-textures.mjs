import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
const base = new URL("../src/assets/planets/", import.meta.url);
const manifest = JSON.parse(await fs.readFile(new URL("sources.json", base), "utf8"));
const data = {};
for (const planet of manifest.records) {
  const entry = {};
  for (const f of planet.files) {
    const bytes = await fs.readFile(new URL(f.path, base));
    if (crypto.createHash("sha256").update(bytes).digest("hex") !== f.sha256)
      throw new Error("Planet source hash mismatch: " + f.path);
    const key = /norm/.test(f.path) ? "normal" : f.path.endsWith(".png") ? "ring" : "map";
    entry[key] = {
      width: f.size[0],
      height: f.size[1],
      src: `data:image/${f.path.endsWith(".png") ? "png" : "jpeg"};base64,${bytes.toString("base64")}`,
    };
  }
  data[planet.id] = entry;
}
const code =
  "// NASA original texture bytes; provenance in planets/sources.json. Generated by tools/pack-planet-textures.mjs.\nexport default " +
  JSON.stringify(data) +
  ";\n";
await fs.writeFile(new URL("../src/assets/planet-textures.js", import.meta.url), code);
console.log(
  JSON.stringify({ planets: Object.keys(data).length, embeddedBytes: Buffer.byteLength(code) }),
);
